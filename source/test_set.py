import json, os, sys
from playwright.sync_api import sync_playwright
W = os.path.dirname(os.path.abspath(__file__))
os.makedirs(os.path.join(W, 't3'), exist_ok=True)
page_html = open(os.path.join(W, 'tengel3.html'), encoding='utf8').read()
hist = json.load(open(os.path.join(W, 'hist.json'), encoding='utf8'))
harness = open(os.path.join(W, 'harness2.py'), encoding='utf8').read()
mock = harness.split('mock = """', 1)[1].split('""" %', 1)[0] % json.dumps(hist, ensure_ascii=False)
skeleton = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{color-scheme:light}body{margin:0;font:14px system-ui}img{max-width:100%%}[hidden]{display:none!important}</style>%s</head><body>%s</body></html>'
open(os.path.join(W, 't3/h.html'), 'w', encoding='utf8').write(skeleton % (mock, page_html))
out = os.path.join(W, 't3')
with sync_playwright() as p:
    b = p.chromium.launch()
    errs = []
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2)
    pg = ctx.new_page()
    pg.on('pageerror', lambda e: errs.append('PAGEERR ' + str(e)))
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'ERR_TUNNEL' not in m.text and 'fonts' not in m.text else None)
    pg.goto('file://' + os.path.join(out, 'h.html')); pg.wait_for_timeout(900)
    pg.click('.tabbar button[data-tab=set]'); pg.wait_for_timeout(300)
    print('A stats:', [x.inner_text() for x in pg.locator('#zoneCard .zr-stat').all()])
    print('sum:', pg.locator('#zoneCard .zsum').inner_text().replace('\n', ' | '))
    pg.screenshot(path=os.path.join(out, 'set_A.png'), full_page=True)
    # B層に 人気→中穴（3着 人気・中穴）を足す
    pg.click('#zoneCard [data-zk=B]'); pg.wait_for_timeout(100)
    pg.click('#zoneCard [data-zact=add]'); pg.wait_for_timeout(100)
    row = pg.locator('#zoneCard .zrow').nth(2)
    row.locator('.zpick[data-f=b] button[data-z="中穴"]').click()
    pg.locator('#zoneCard .zrow').nth(2).locator('.zpick[data-f=t] button[data-z="人気"]').click()
    pg.locator('#zoneCard .zrow').nth(2).locator('.zpick[data-f=t] button[data-z="中穴"]').click()
    print('B rows:', [x.inner_text() for x in pg.locator('#zoneCard .zr-label').all()], '| msg:', pg.locator('#zmsg').inner_text())
    print('B stats:', [x.inner_text() for x in pg.locator('#zoneCard .zr-stat').all()])
    pg.screenshot(path=os.path.join(out, 'set_B_edit.png'), full_page=True)
    pg.click('#zoneCard [data-zact=save]'); pg.wait_for_timeout(300)
    print('after save msg:', pg.locator('#zmsg').inner_text(), '| ls:', pg.evaluate("localStorage.getItem('tengel.zones')")[:120])
    print('ver:', pg.locator('.brand .ver').inner_text())
    pg.click('.tabbar button[data-tab=judge]'); pg.wait_for_timeout(300)
    print('judge zones:', [x.inner_text().replace('\n', ' ') for x in pg.locator('#result .zflow').all()])
    print('chips:', pg.locator('#result .chips').inner_text())
    txt = pg.locator('#outText').inner_text()
    print('text has custom note:', 'カスタム買い目' in txt, '| T3:', [l for l in txt.split('\n') if '第3' in l][:4])
    pg.locator('#result').screenshot(path=os.path.join(out, 'judge_custom.png'))
    # reload: persists
    pg.reload(); pg.wait_for_timeout(900)
    print('after reload zones:', [x.inner_text().replace('\n', ' ') for x in pg.locator('#result .zflow').all()])
    pg.click('.tabbar button[data-tab=stats]'); pg.wait_for_timeout(400)
    print('⑦ title:', pg.locator('#statsBody h2', has_text='⑦').inner_text())
    pg.screenshot(path=os.path.join(out, 'stats_custom.png'), full_page=True)
    # reset all
    pg.click('.tabbar button[data-tab=set]'); pg.wait_for_timeout(200)
    pg.locator('#zoneCard details summary').click(); pg.click('#zoneCard [data-zact=allDef]'); pg.wait_for_timeout(300)
    print('after reset:', pg.locator('#zmsg').inner_text(), '| ls:', pg.evaluate("localStorage.getItem('tengel.zones')"), '| ver:', pg.locator('.brand .ver').inner_text())
    pg.click('.tabbar button[data-tab=judge]'); pg.wait_for_timeout(300)
    print('judge zones after reset:', [x.inner_text().replace('\n', ' ') for x in pg.locator('#result .zflow').all()])
    print('ERRORS:', errs)
    b.close()
