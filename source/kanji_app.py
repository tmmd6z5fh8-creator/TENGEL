KEEP = ('はじめまして', 'ご利用にあたって')       # ひらがなの まま 守る 言い回し
_RX = [(re.compile(p), r) for p, r in RULES]


def convert(t, hits=None):
    """文を 漢字に そろえる（hits に リストを わたすと (規則の 番号, 前, 後) を 足す）"""
    for i, w in enumerate(KEEP):
        t = t.replace(w, f'\x00{i}\x00')
    for i, (rx, rep) in enumerate(_RX):
        def f(m, i=i, rep=rep):
            r = m.expand(rep)
            if hits is not None: hits.append((i, m.group(0), r))
            return r
        t = rx.sub(f, t)
    for i, w in enumerate(KEEP):
        t = t.replace(f'\x00{i}\x00', w)
    return t
